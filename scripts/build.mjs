#!/usr/bin/env node
// Builds every output from the DTCG token sources and the CSS/JS sources.
// No dependencies: Node 20+ only. Run with `npm run build`.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, rmSync, existsSync, cpSync } from 'node:fs';
import { createRequire } from 'node:module';
import * as nativeMod from './native.mjs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const PREFIX = 'lm';
const banner = `/* Larkmoor v${pkg.version}. Generated by scripts/build.mjs. Do not edit. */\n`;

// ---------- load ----------

const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));
const dir = (d) => readdirSync(join(root, d)).filter((f) => f.endsWith('.tokens.json')).sort().map((f) => join(root, d, f));

export function deepMerge(target, source) {
  for (const [key, value] of Object.entries(source)) {
    if (value && typeof value === 'object' && !Array.isArray(value) && !('$value' in value) && target[key] && typeof target[key] === 'object') {
      deepMerge(target[key], value);
    } else {
      target[key] = structuredClone(value);
    }
  }
  return target;
}

/** Flattens a token tree into Map(path -> { value, type, description, extensions }). Group $type is inherited. */
export function flatten(tree, path = [], inheritedType, out = new Map()) {
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$') || node === null || typeof node !== 'object') continue;
    const type = node.$type ?? inheritedType;
    if ('$value' in node) {
      out.set([...path, key].join('.'), { value: node.$value, type, description: node.$description, extensions: node.$extensions, deprecated: node.$deprecated });
    } else {
      flatten(node, [...path, key], type, out);
    }
  }
  return out;
}

const ALIAS = /^\{([^{}]+)\}$/;

/** Follows aliases to the final token. Throws on missing targets and cycles. */
export function resolve(tokens, path, seen = []) {
  const token = tokens.get(path);
  if (!token) throw new Error(`Unknown token "${path}"${seen.length ? ` (referenced from ${seen.at(-1)})` : ''}`);
  if (seen.includes(path)) throw new Error(`Alias cycle: ${[...seen, path].join(' -> ')}`);
  const m = typeof token.value === 'string' && token.value.match(ALIAS);
  if (!m) return { ...token, path };
  const target = resolve(tokens, m[1], [...seen, path]);
  return { ...target, path, type: token.type ?? target.type, aliasOf: m[1] };
}

// ---------- values -> CSS ----------

const varName = (path) => `--${PREFIX}-${path.replaceAll('.', '-')}`;
const dimension = (d) => `${d.value}${d.unit}`;
const fmt = (n) => Number(n.toFixed(4)).toString();

function colorToCss(c) {
  if (typeof c === 'string') return c;
  if (c.alpha !== undefined && c.alpha < 1) {
    const [r, g, b] = c.components.map((v) => Math.round(v * 255));
    return `rgb(${r} ${g} ${b} / ${c.alpha})`;
  }
  return c.hex ?? `rgb(${c.components.map((v) => Math.round(v * 255)).join(' ')})`;
}

export function toCss(token) {
  const ext = token.extensions ?? {};
  if (ext['com.larkmoor.css']) return ext['com.larkmoor.css'];
  if (ext['com.larkmoor.fluid']) {
    const f = ext['com.larkmoor.fluid'];
    return `clamp(${dimension(f.min)}, ${f.preferred}, ${dimension(f.max)})`;
  }
  const v = token.value;
  switch (token.type) {
    case 'color': return colorToCss(v);
    case 'dimension': return dimension(v);
    case 'duration': return `${v.value}${v.unit}`;
    case 'cubicBezier': return `cubic-bezier(${v.map(fmt).join(', ')})`;
    case 'fontFamily': return (Array.isArray(v) ? v : [v]).map((f) => (/[\s\d]/.test(f) && !f.startsWith('-') ? `"${f}"` : f)).join(', ');
    case 'fontWeight': case 'number': return String(v);
    case 'shadow': return [v].flat().map((s) => `${dimension(s.offsetX)} ${dimension(s.offsetY)} ${dimension(s.blur)} ${dimension(s.spread)} ${colorToCss(s.color)}`).join(', ');
    default: throw new Error(`No CSS transform for $type "${token.type}"`);
  }
}

/** One declaration per token. Aliases stay live as var() so themes can override a single layer. */
function declarations(tokens, only) {
  const lines = [];
  for (const path of only ?? tokens.keys()) {
    const token = tokens.get(path);
    const m = typeof token.value === 'string' && token.value.match(ALIAS);
    const value = m ? `var(${varName(m[1])})` : toCss(resolve(tokens, path));
    lines.push(`  ${varName(path)}: ${value};`);
  }
  return lines.join('\n');
}

// ---------- build ----------

export function loadAll() {
  const base = {};
  for (const f of [...dir('tokens/foundation'), ...dir('tokens/semantic')]) deepMerge(base, readJson(f));
  const themes = {};
  for (const f of dir('tokens/themes')) {
    const json = readJson(f);
    const meta = json.$extensions['com.larkmoor.theme'];
    themes[meta.name] = { meta, json };
  }
  return { base, themes };
}

/** Full token map for a theme: base, then the theme it extends, then the theme itself. */
export function themeTokens(base, themes, name) {
  const chain = [];
  for (let t = themes[name]; t; t = themes[t.meta.extends]) chain.unshift(t);
  const merged = deepMerge(structuredClone(base), {});
  for (const t of chain) deepMerge(merged, t.json);
  return flatten(merged);
}

function validate(tokens, label) {
  const problems = [];
  for (const path of tokens.keys()) {
    try {
      const t = resolve(tokens, path);
      if (!t.type) problems.push(`${path}: no $type (set it on the token or a parent group)`);
      else toCss(t);
    } catch (e) { problems.push(`${path}: ${e.message}`); }
  }
  if (problems.length) throw new Error(`Token errors in ${label}:\n  ${problems.join('\n  ')}`);
}

function build() {
  rmSync(dist, { recursive: true, force: true });
  mkdirSync(join(dist, 'themes'), { recursive: true });
  mkdirSync(join(dist, 'fonts'), { recursive: true });

  const { base, themes } = loadAll();
  const tokens = flatten(base);
  validate(tokens, 'base');

  // tokens.css: foundation + default semantic layer
  writeFileSync(join(dist, 'tokens.css'), `${banner}:root {\n${declarations(tokens)}\n  color-scheme: light;\n}\n`);

  // themes/<name>.css: only the semantic paths the theme (and what it extends) changes
  const resolvedThemes = { default: tokens };
  for (const name of Object.keys(themes)) {
    const full = themeTokens(base, themes, name);
    validate(full, `theme ${name}`);
    resolvedThemes[name] = full;
    const changed = new Set();
    for (let t = themes[name]; t; t = themes[t.meta.extends]) for (const p of flatten(t.json).keys()) changed.add(p);
    const scheme = themes[name].meta.scheme;
    const decls = declarations(full, [...changed].sort());
    let css = `${banner}/* ${themes[name].meta.description} */\n[data-lm-theme="${name}"] {\n${decls}\n  color-scheme: ${scheme};\n  background-color: var(--lm-color-bg);\n  color: var(--lm-color-text);\n}\n`;
    // A dark theme can be the automatic partner of a light one: pages that opt in with
    // data-lm-color-scheme="auto" switch when the visitor's device is set to dark.
    const darkOf = themes[name].meta.darkOf;
    if (darkOf) {
      const target = darkOf === 'default' ? '[data-lm-color-scheme="auto"]:not([data-lm-theme])' : `[data-lm-color-scheme="auto"][data-lm-theme="${darkOf}"]`;
      css += `\n/* Automatic: ${darkOf} switches to ${name} when the device prefers dark */\n@media (prefers-color-scheme: dark) {\n  ${target} {\n${decls.replaceAll('\n', '\n  ')}\n    color-scheme: dark;\n  }\n}\n`;
    }
    // A high-contrast theme is the automatic partner of another theme: pages that opt in with
    // data-lm-contrast="auto" switch when the device asks for more contrast (iOS/macOS Increase
    // Contrast, Windows contrast themes off, Android high contrast where the browser reports it).
    const contrastOf = themes[name].meta.contrastOf;
    if (contrastOf) {
      const block = (sel) => `  ${sel} {\n${decls.replaceAll('\n', '\n  ')}\n    color-scheme: ${scheme};\n  }`;
      const rules = [];
      const ofMeta = themes[contrastOf]?.meta;
      if (contrastOf === 'default') {
        rules.push(['(prefers-contrast: more)', '[data-lm-contrast="auto"]:not([data-lm-theme])']);
      } else {
        // the theme on the page root, or on a band inside it (e.g. an inverse footer)
        rules.push(['(prefers-contrast: more)', `[data-lm-contrast="auto"][data-lm-theme="${contrastOf}"],\n  [data-lm-contrast="auto"] [data-lm-theme="${contrastOf}"]`]);
      }
      // the partner of an automatic dark theme also follows automatic dark mode (higher specificity wins)
      if (ofMeta?.darkOf) {
        const lightSel = ofMeta.darkOf === 'default' ? ':not([data-lm-theme])' : `[data-lm-theme="${ofMeta.darkOf}"]`;
        rules.push(['(prefers-contrast: more) and (prefers-color-scheme: dark)', `[data-lm-contrast="auto"][data-lm-color-scheme="auto"]${lightSel}`]);
      }
      for (const [query, sel] of rules) css += `\n/* Automatic: ${contrastOf} switches to ${name} when the device asks for more contrast */\n@media ${query} {\n${block(sel)}\n}\n`;
    }
    writeFileSync(join(dist, 'themes', `${name}.css`), css);
  }

  // tokens.json: resolved values for every theme, for tests, docs and non-CSS platforms
  const resolvedJson = {};
  for (const [name, map] of Object.entries(resolvedThemes)) {
    resolvedJson[name] = Object.fromEntries([...map.keys()].map((p) => [p, toCss(resolve(map, p))]));
  }
  writeFileSync(join(dist, 'tokens.json'), JSON.stringify({ version: pkg.version, themes: resolvedJson }, null, 2) + '\n');

  // breakpoints: CSS custom properties can't be used inside @media, so they ship as constants
  const bp = Object.fromEntries([...tokens.keys()].filter((p) => p.startsWith('breakpoint.')).map((p) => [p.split('.')[1], tokens.get(p).value.value]));
  writeFileSync(join(dist, 'breakpoints.json'), JSON.stringify(bp, null, 2) + '\n');
  writeFileSync(join(dist, 'breakpoints.mjs'), `${banner}export const breakpoints = Object.freeze(${JSON.stringify(bp)});\n/** e.g. media('medium') -> "(max-width: 899.98px)" for "below medium" */\nexport const below = (name) => \`(max-width: \${breakpoints[name] - 0.02}px)\`;\nexport const atLeast = (name) => \`(min-width: \${breakpoints[name]}px)\`;\n`);
  writeFileSync(join(dist, 'breakpoints.d.ts'), `export type Breakpoint = ${Object.keys(bp).map((k) => `'${k}'`).join(' | ')};\nexport declare const breakpoints: Readonly<Record<Breakpoint, number>>;\nexport declare function below(name: Breakpoint): string;\nexport declare function atLeast(name: Breakpoint): string;\n`);
  writeFileSync(join(dist, '_breakpoints.scss'), `// Generated. Do not edit.\n${Object.entries(bp).map(([k, v]) => `$lm-bp-${k}: ${v}px;`).join('\n')}\n`);

  // larkmoor.css: tokens + every source stylesheet, in the order index.txt lists
  const order = readFileSync(join(root, 'src/css/index.txt'), 'utf8').split('\n').map((s) => s.trim()).filter((s) => s && !s.startsWith('#'));
  // Every stylesheet lives in a cascade layer, so any unlayered CSS on the page (a site theme, a CMS)
  // overrides Larkmoor without specificity fights. Order: base < layout < components < utilities.
  const layerOf = (f) => (f === 'base.css' || f === 'typography.css' ? 'lm.base' : f === 'layout.css' ? 'lm.layout' : f === 'motion.css' || f === 'forced-colors.css' ? 'lm.utilities' : 'lm.components');
  const parts = order.map((f) => `/* ---- ${f} ---- */\n@layer ${layerOf(f)} {\n${readFileSync(join(root, 'src/css', f), 'utf8').trim()}\n}\n`);
  writeFileSync(join(dist, 'larkmoor.css'), `${banner}@layer lm.base, lm.layout, lm.components, lm.utilities;\n${readFileSync(join(dist, 'tokens.css'), 'utf8').replace(banner, '')}\n${parts.join('\n')}`);

  // fonts (web woff2 + native ttf)
  cpSync(join(root, 'fonts'), join(dist, 'fonts'), { recursive: true });
  copyFileSync(join(root, 'src/css/fonts.css'), join(dist, 'fonts.css'));

  // behaviours: plain ES modules with JSDoc, types alongside
  for (const f of readdirSync(join(root, 'src/js'))) copyFileSync(join(root, 'src/js', f), join(dist, f));

  buildNative(base, themes, resolvedThemes);

  const files = readdirSync(dist, { recursive: true }).filter((f) => !existsSync(join(dist, f)) || f.includes('.'));
  console.log(`Built ${files.length} files into dist/ from ${tokens.size} base tokens and ${Object.keys(themes).length} themes.`);
}

// ---------- native platforms ----------

function buildNative(base, themes, resolvedThemes) {
  const { nativeModel, reactNativeTokens, reactNativeTokensDts, swift, kotlinCore, compose } = nativeMod;
  const rawSemantic = readJson(join(root, 'tokens/semantic/semantic.tokens.json'));
  const models = {};
  for (const [name, map] of Object.entries(resolvedThemes)) {
    models[name] = { name, scheme: name === 'default' ? 'light' : themes[name].meta.scheme, ...nativeModel(map, rawSemantic, resolve) };
  }
  // high-contrast partner for each theme that has one (used for iOS Increase Contrast, Android contrast level)
  const contrast = Object.fromEntries(Object.entries(themes).filter(([, t]) => t.meta.contrastOf).map(([n, t]) => [t.meta.contrastOf, n]));
  mkdirSync(join(dist, 'native'), { recursive: true });
  writeFileSync(join(dist, 'native/tokens.json'), JSON.stringify({ version: pkg.version, highContrast: contrast, themes: models }, null, 2) + '\n');
  // Hand-written native components live in src/ios and src/android and ship next to the generated tokens.
  mkdirSync(join(dist, 'ios'), { recursive: true });
  writeFileSync(join(dist, 'ios/Larkmoor.swift'), swift(pkg.version, models, contrast));
  for (const f of readdirSync(join(root, 'src/ios'))) copyFileSync(join(root, 'src/ios', f), join(dist, 'ios', f));
  mkdirSync(join(dist, 'android'), { recursive: true });
  writeFileSync(join(dist, 'android/LarkmoorTokens.kt'), kotlinCore(pkg.version, models, contrast));
  writeFileSync(join(dist, 'android/LarkmoorTheme.kt'), compose(pkg.version));
  for (const f of readdirSync(join(root, 'src/android'))) copyFileSync(join(root, 'src/android', f), join(dist, 'android', f));

  // React Native: generated tokens + hand-written components, compiled to JS with esbuild
  const rnSrc = join(root, 'src/react-native');
  writeFileSync(join(rnSrc, 'tokens.generated.ts'), reactNativeTokens(pkg.version, models, contrast));
  const rnOut = join(dist, 'react-native');
  mkdirSync(rnOut, { recursive: true });
  let esbuild;
  try { esbuild = createRequire(import.meta.url)('esbuild'); } catch { console.warn('esbuild not installed: skipped compiling src/react-native (run npm install).'); return; }
  const entries = readdirSync(rnSrc).filter((f) => /\.tsx?$/.test(f) && !f.endsWith('.d.ts')).map((f) => join(rnSrc, f));
  esbuild.buildSync({ entryPoints: entries, outdir: rnOut, format: 'esm', jsx: 'automatic', target: 'es2020', platform: 'neutral', logLevel: 'warning', logOverride: { 'unsupported-require-call': 'silent' } }); // Metro resolves the font require() calls
  for (const f of readdirSync(rnSrc).filter((f) => f.endsWith('.d.ts'))) copyFileSync(join(rnSrc, f), join(rnOut, f));
  for (const f of readdirSync(join(rnSrc, 'types')).filter((f) => f.endsWith('.d.ts'))) copyFileSync(join(rnSrc, 'types', f), join(rnOut, f));
  writeFileSync(join(rnOut, 'tokens.generated.d.ts'), reactNativeTokensDts(pkg.version, models, contrast));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try { build(); } catch (e) { console.error(e.message); process.exit(1); }
}
